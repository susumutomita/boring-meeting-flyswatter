export const pickMeetingTip = (seed: number): string => {
  if (!Number.isFinite(seed) || meetingTips.length === 0) {
    return meetingTips[0] ?? '';
  }
  const index = Math.abs(Math.floor(seed)) % meetingTips.length;
  return meetingTips[index];
};
